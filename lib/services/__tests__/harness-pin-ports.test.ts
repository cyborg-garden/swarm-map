import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest'
import fs from 'fs'
import os from 'os'
import path from 'path'
import { HarnessService } from '../harness'
import { Storage } from '../storage'
import { DockerService } from '../docker'
import { AuditService } from '../audit'
import { ConfigService } from '../config'
import type { RestartMode } from '@/lib/types'

vi.mock('../docker')

// What a pre-loopback compose on the Mini looks like: API published on all
// interfaces (no host_ip).
const OLD = `# Generated by hermes-swarm-map — agent: a
services:
  hermes-a:
    image: img:1
    container_name: hermes-a
    ports:
      - published: 8652
        target: 8642
    volumes:
      - /d/a:/opt/data
`

class TestHarness extends HarnessService {
  constructor(s: Storage, d: DockerService, a: AuditService, c: ConfigService, private compose: string) {
    super(s, d, a, c)
  }
  get(id: string): ReturnType<HarnessService['get']> {
    return { id, name: 'a', serviceName: 'hermes-a', composeFile: this.compose } as unknown as ReturnType<HarnessService['get']>
  }
}

let tmp: string, composeFile: string, docker: DockerService, audit: AuditService, config: ConfigService, svc: TestHarness

beforeEach(() => {
  tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'pin-'))
  composeFile = path.join(tmp, 'docker-compose.yml')
  fs.writeFileSync(composeFile, OLD, { mode: 0o640 })
  docker = new DockerService()
  const storage = new Storage(tmp)
  audit = new AuditService(storage)
  config = new ConfigService(storage)
  config.updateSettings({ apiBindHost: '127.0.0.1' })
  svc = new TestHarness(storage, docker, audit, config, composeFile)
})
afterEach(() => fs.rmSync(tmp, { recursive: true, force: true }))

const pinned = () => fs.readFileSync(composeFile, 'utf-8').includes('- host_ip: 127.0.0.1\n        published: 8652')

describe('old composes are pinned to loopback before the container is recreated', () => {
  for (const mode of ['recreate', 'rebuild', 'purge'] as RestartMode[]) {
    it(`restart(${mode}) pins the ports, then recreates`, () => {
      vi.mocked(docker.restart).mockImplementation(() => {
        // The file must already be pinned when docker runs.
        expect(pinned()).toBe(true)
      })
      svc.restart('h_a', mode)
      expect(docker.restart).toHaveBeenCalledOnce()
      expect(pinned()).toBe(true)
    })
  }

  it('restart(quick) leaves the file alone (no recreate, so it would lie)', () => {
    svc.restart('h_a', 'quick')
    expect(fs.readFileSync(composeFile, 'utf-8')).toBe(OLD)
  })

  it('start() pins too (up -d recreates on a changed compose)', () => {
    vi.mocked(docker.start).mockImplementation(() => { expect(pinned()).toBe(true) })
    svc.start('h_a')
    expect(docker.start).toHaveBeenCalledOnce()
  })

  it('keeps the file mode, leaves no temp file, and audits the change', () => {
    svc.restart('h_a', 'recreate')
    expect(fs.statSync(composeFile).mode & 0o777).toBe(0o640)
    expect(fs.readdirSync(tmp).filter((f) => f.includes('.tmp-'))).toEqual([])
    expect(audit.query({}).some((e) => e.what === 'compose:pin-ports' && e.target === 'a')).toBe(true)
  })

  it('a host of 0.0.0.0 (Linux default) changes nothing', () => {
    config.updateSettings({ apiBindHost: '0.0.0.0' })
    svc.restart('h_a', 'recreate')
    expect(fs.readFileSync(composeFile, 'utf-8')).toBe(OLD)
  })
})
