describe('driftTargets', () => {
  let root: string
  let composeBaseDir: string

  beforeEach(() => {
    root = fs.mkdtempSync(path.join(os.tmpdir(), 'drift-enum-'))
    composeBaseDir = path.join(root, 'compose')
    for (const [name, svc] of [
      ['iris', 'hermes-iris'],
      ['seraph-doer', 'seraph-doer'],
      ['seraph-thinker', 'seraph-thinker'],
    ] as const) {
      fs.mkdirSync(path.join(composeBaseDir, name), { recursive: true })
      fs.writeFileSync(
        path.join(composeBaseDir, name, 'docker-compose.yml'),
        ['services:', `  ${svc}:`, '    build: /src/hermes-agent-mt', `    container_name: ${svc}`].join('\n'),
      )
    }
  })
  afterEach(() => {
    fs.rmSync(root, { recursive: true, force: true })
  })

  it('includes seraph-* agents that no `docker ps | grep hermes-` would ever find', () => {
    // Only iris is discovered/running. The three seraph services are keyed
    // seraph-* AND have no container — invisible to both halves of a grep.
    const targets = driftTargets({
      harnesses: [harness({ id: 'h_iris', name: 'iris', serviceName: 'hermes-iris', status: 'running' })],
      composeBaseDir,
    })
    expect(targets.map((t) => t.name).sort()).toEqual(['iris', 'seraph-doer', 'seraph-thinker'])
    const doer = targets.find((t) => t.name === 'seraph-doer')!
    expect(doer.running).toBe(false)
    expect(doer.service).toBe('seraph-doer')
    expect(doer.harnessId).toBe(harnessIdForName('seraph-doer'))
  })

  it('does not double-count an agent present in both the registry and compose dirs', () => {
    const targets = driftTargets({
      harnesses: [harness({ id: 'h_iris', name: 'iris', serviceName: 'hermes-iris' })],
      composeBaseDir,
    })
    expect(targets.filter((t) => t.name === 'iris')).toHaveLength(1)
  })

  it('backfills a compose file onto a registry row that has none', () => {
    const targets = driftTargets({
      harnesses: [harness({ id: 'h_iris', name: 'iris', serviceName: 'hermes-iris' })],
      composeBaseDir,
    })
    expect(targets.find((t) => t.name === 'iris')!.composeFile).toBe(
      path.join(composeBaseDir, 'iris', 'docker-compose.yml'),
    )
  })

  it('skips Letta rows — they are Postgres records, not containers', () => {
    const targets = driftTargets({
      harnesses: [
        harness({ id: 'h_letta_a', name: 'letta-a', runtime: 'letta' }),
        harness({ id: 'h_letta_srv', name: 'letta-srv', runtime: 'letta-server' }),
      ],
      composeBaseDir,
    })
    expect(targets.map((t) => t.name)).not.toContain('letta-a')
    expect(targets.map((t) => t.name)).not.toContain('letta-srv')
  })

  it('keeps a registry-only agent with no compose dir', () => {
    const targets = driftTargets({
      harnesses: [harness({ id: 'h_ghost', name: 'ghost', serviceName: 'hermes-ghost', status: 'stopped' })],
      composeBaseDir,
    })
    expect(targets.find((t) => t.name === 'ghost')).toBeTruthy()
    expect(targets.find((t) => t.name === 'ghost')!.running).toBe(false)
  })
})

