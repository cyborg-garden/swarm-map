describe('readComposeService', () => {
  it('reads a long-form build context for a hermes-* service', () => {
    const compose = [
      '# Generated by hermes-swarm-map — agent: iris',
      'services:',
      '  hermes-iris:',
      '    build:',
      '      context: /Users/juni/Documents/GitHub/hermes-agent-mt',
      '      dockerfile: Dockerfile',
      '    container_name: hermes-iris',
      '    restart: unless-stopped',
      'networks:',
      '  default:',
    ].join('\n')
    expect(readComposeService(compose)).toEqual({
      service: 'hermes-iris',
      buildContext: '/Users/juni/Documents/GitHub/hermes-agent-mt',
      containerName: 'hermes-iris',
      image: null,
    })
  })

  it('reads a shorthand build context for a seraph-* service', () => {
    // The whole reason this parser exists instead of reusing
    // readComposeBuildContext, which anchors on `^  hermes-`.
    const compose = [
      'services:',
      '  seraph-doer:',
      '    build: /Users/juni/Documents/GitHub/hermes-agent-mt',
      '    container_name: seraph-doer',
      '    restart: unless-stopped',
    ].join('\n')
    const parsed = readComposeService(compose)
    expect(parsed.service).toBe('seraph-doer')
    expect(parsed.buildContext).toBe('/Users/juni/Documents/GitHub/hermes-agent-mt')
    expect(parsed.containerName).toBe('seraph-doer')
  })

  it('reads an image-only service and reports no build context', () => {
    const compose = ['services:', '  hermes-mare:', '    image: nimblecoorg/hermes-agent-mt:v1'].join('\n')
    expect(readComposeService(compose)).toMatchObject({
      service: 'hermes-mare',
      buildContext: null,
      image: 'nimblecoorg/hermes-agent-mt:v1',
    })
  })

  it('does not mistake a networks: key for a service', () => {
    const compose = [
      'networks:',
      '  default:',
      '    name: hermes',
      'services:',
      '  hermes-iris:',
      '    build: /src',
      '    container_name: hermes-iris',
    ].join('\n')
    const parsed = readComposeService(compose)
    expect(parsed.service).toBe('hermes-iris')
    expect(parsed.buildContext).toBe('/src')
  })

  it('returns nothing for a compose with no services: block', () => {
    expect(readComposeService('networks:\n  default:\n')).toEqual({
      service: null,
      buildContext: null,
      containerName: null,
      image: null,
    })
  })

  it('stops at the next service key rather than bleeding into it', () => {
    const compose = [
      'services:',
      '  hermes-a:',
      '    container_name: hermes-a',
      '  hermes-b:',
      '    build: /elsewhere',
      '    container_name: hermes-b',
    ].join('\n')
    const parsed = readComposeService(compose)
    expect(parsed.service).toBe('hermes-a')
    expect(parsed.containerName).toBe('hermes-a')
    expect(parsed.buildContext).toBeNull()
  })
})

// --- buildSourceHead -------------------------------------------------------

describe('buildSourceHead', () => {
  let root: string
  beforeEach(() => {
    root = fs.mkdtempSync(path.join(os.tmpdir(), 'drift-head-'))
  })
  afterEach(() => {
    fs.rmSync(root, { recursive: true, force: true })
  })

  it('returns the full HEAD sha, branch and commit time', () => {
    const { dir, shas } = makeRepo(root, 3)
    const head = buildSourceHead(dir)
    expect(head.head).toBe(shas[2])
    expect(head.head).toMatch(/^[0-9a-f]{40}$/)
    expect(head.branch).toBe('main')
    expect(head.error).toBeNull()
    expect(head.headCommittedAt).toBe(Date.parse('2026-08-03T00:00:00Z'))
  })

  it('counts how far the checkout is behind its own upstream', () => {
    const { dir } = makeRepo(root, 4)
    // Stand up a bare "remote", push, then rewind the local branch two commits.
    const remote = path.join(root, 'remote.git')
    execFileSync('git', ['init', '-q', '--bare', '-b', 'main', remote], { stdio: 'pipe' })
    git(dir, ['remote', 'add', 'origin', remote])
    git(dir, ['push', '-q', '-u', 'origin', 'main'])
    git(dir, ['reset', '-q', '--hard', 'HEAD~2'])

    const head = buildSourceHead(dir)
    expect(head.upstream).toBe('origin/main')
    expect(head.behindUpstream).toBe(2)
  })

  it('reports an error (never a sha) for a missing dir', () => {
    const head = buildSourceHead(path.join(root, 'nope'))
    expect(head.head).toBeNull()
    expect(head.error).toContain('does not exist')
  })

  it('reports an error (never a sha) for a non-git dir', () => {
    const plain = fs.mkdtempSync(path.join(root, 'plain-'))
    const head = buildSourceHead(plain)
    expect(head.head).toBeNull()
    expect(head.error).toContain('not a git repo')
  })

  it('does not fetch — behindUpstream reflects only refs already on disk', () => {
    const { dir } = makeRepo(root, 2)
    const remote = path.join(root, 'remote2.git')
    execFileSync('git', ['init', '-q', '--bare', '-b', 'main', remote], { stdio: 'pipe' })
    git(dir, ['remote', 'add', 'origin', remote])
    git(dir, ['push', '-q', '-u', 'origin', 'main'])
    const beforeFetchHead = fs.existsSync(path.join(dir, '.git', 'FETCH_HEAD'))

    // Advance the remote behind the local repo's back via a second clone.
    const other = path.join(root, 'other')
    execFileSync('git', ['clone', '-q', '-b', 'main', remote, other], { stdio: 'pipe' })
    fs.writeFileSync(path.join(other, 'new.txt'), 'x\n')
    git(other, ['add', '-A'])
    git(other, ['commit', '-q', '-m', 'remote-only'])
    git(other, ['push', '-q', 'origin', 'main'])

    // Read-only: we still see 0, because nothing fetched. That is the honest
    // answer for a module that must not touch the network.
    expect(buildSourceHead(dir).behindUpstream).toBe(0)
    expect(fs.existsSync(path.join(dir, '.git', 'FETCH_HEAD'))).toBe(beforeFetchHead)
  })
})

// --- commitGap -------------------------------------------------------------

describe('commitGap', () => {
  let root: string
  beforeEach(() => {
    root = fs.mkdtempSync(path.join(os.tmpdir(), 'drift-gap-'))
  })
  afterEach(() => {
    fs.rmSync(root, { recursive: true, force: true })
  })

  it('counts commits AND wall-clock age between the two commits', () => {
    // 5 commits, one day apart: HEAD is c4, container built at c0.
    const { dir, shas } = makeRepo(root, 5)
    const g = commitGap(dir, shas[0], shas[4])
    expect(g.commitsBehind).toBe(4)
    expect(g.ageBehindMs).toBe(4 * 86_400_000)
    expect(g.detail).toBeNull()
  })

  it('reports zero-commit gap for the same commit', () => {
    const { dir, shas } = makeRepo(root, 2)
    const g = commitGap(dir, shas[1], shas[1])
    expect(g.commitsBehind).toBe(0)
    expect(g.ageBehindMs).toBe(0)
  })

  it('returns null counts — never zero — when the container commit is unknown here', () => {
    // Unknown must not be reported as "0 behind"; that is the zero-when-unknown
    // misread that makes a stale agent look fine.
    const { dir, shas } = makeRepo(root, 2)
    const g = commitGap(dir, A_SHA, shas[1])
    expect(g.commitsBehind).toBeNull()
    expect(g.ageBehindMs).toBeNull()
    expect(g.detail).toContain('not present in')
  })

  it('flags a diverged/rolled-back source instead of implying a clean N behind', () => {
    const { dir, shas } = makeRepo(root, 3)
    // Source rolls back to c0; the container still runs c2.
    const g = commitGap(dir, shas[2], shas[0])
    expect(g.commitsBehind).toBe(0)
    expect(g.detail).toContain('not an ancestor')
  })
})

