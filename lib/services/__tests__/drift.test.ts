// --- helpers ---------------------------------------------------------------

function git(dir: string, args: string[]): string {
  return execFileSync('git', ['-C', dir, ...args], {
    stdio: 'pipe',
    env: {
      ...process.env,
      GIT_AUTHOR_NAME: 'T',
      GIT_AUTHOR_EMAIL: 't@example.com',
      GIT_COMMITTER_NAME: 'T',
      GIT_COMMITTER_EMAIL: 't@example.com',
    },
  })
    .toString()
    .trim()
}

/** A repo with `n` commits, each stamped `dayStep` days apart. */
function makeRepo(root: string, n: number, dayStep = 1): { dir: string; shas: string[] } {
  const dir = fs.mkdtempSync(path.join(root, 'src-'))
  execFileSync('git', ['init', '-q', '-b', 'main', dir], { stdio: 'pipe' })
  const shas: string[] = []
  const base = Date.parse('2026-08-01T00:00:00Z')
  for (let i = 0; i < n; i++) {
    fs.writeFileSync(path.join(dir, `f${i}.txt`), `${i}\n`)
    const when = new Date(base + i * dayStep * 86_400_000).toISOString()
    execFileSync('git', ['-C', dir, 'add', '-A'], { stdio: 'pipe' })
    execFileSync('git', ['-C', dir, 'commit', '-q', '-m', `c${i}`], {
      stdio: 'pipe',
      env: {
        ...process.env,
        GIT_AUTHOR_NAME: 'T',
        GIT_AUTHOR_EMAIL: 't@example.com',
        GIT_COMMITTER_NAME: 'T',
        GIT_COMMITTER_EMAIL: 't@example.com',
        GIT_AUTHOR_DATE: when,
        GIT_COMMITTER_DATE: when,
      },
    })
    shas.push(git(dir, ['rev-parse', 'HEAD']))
  }
  return { dir, shas }
}

const A_SHA = 'a'.repeat(40)
const B_SHA = 'b'.repeat(40)

function fakeDocker(opts: {
  sha?: string | null
  diff?: string[]
  execThrows?: boolean
} = {}) {
  return {
    execInContainer: vi.fn(async () => {
      if (opts.execThrows) throw new Error('no such container')
      if (opts.sha == null) throw new Error('cat: No such file or directory')
      return opts.sha + '\n'
    }),
    diffContainer: vi.fn(async () => opts.diff ?? []),
  }
}

function target(over: Partial<DriftTarget> = {}): DriftTarget {
  return {
    harnessId: 'h_iris',
    name: 'iris',
    service: 'hermes-iris',
    container: 'hermes-iris',
    composeFile: null,
    running: true,
    ...over,
  }
}

