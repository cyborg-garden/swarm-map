describe('containerBuildSha', () => {
  it('reads the sha the Dockerfile stamped in', async () => {
    const docker = fakeDocker({ sha: A_SHA })
    await expect(containerBuildSha(docker, 'hermes-iris')).resolves.toBe(A_SHA)
    expect(docker.execInContainer).toHaveBeenCalledWith(
      'hermes-iris',
      ['cat', BUILD_SHA_PATH],
      expect.any(Number),
    )
  })

  it('returns null when the provenance file is absent (pre-build-arg image)', async () => {
    await expect(containerBuildSha(fakeDocker({ sha: null }), 'hermes-iris')).resolves.toBeNull()
  })

  it('returns null for non-sha content rather than trusting it', async () => {
    const docker = { execInContainer: vi.fn(async () => 'unknown\n'), diffContainer: vi.fn(async () => []) }
    await expect(containerBuildSha(docker, 'hermes-iris')).resolves.toBeNull()
  })
})

describe('hotPatched', () => {
  it('is true when agent code under /opt/hermes/agent was modified', async () => {
    const docker = fakeDocker({ diff: ['C /opt', `C ${AGENT_CODE_PATH}`, `C ${AGENT_CODE_PATH}/tools.py`] })
    await expect(hotPatched(docker, 'hermes-iris')).resolves.toBe(true)
  })

  it('is false for bind-mount noise, which every container shows', async () => {
    // Real `docker diff hermes-iris` output — mounts, not hot-patching.
    const docker = fakeDocker({ diff: ['C /opt', 'A /opt/iris', 'A /opt/iris-intake', 'A /opt/iris-state'] })
    await expect(hotPatched(docker, 'hermes-iris')).resolves.toBe(false)
  })

  it('does not match a sibling path that merely shares the prefix', async () => {
    const docker = fakeDocker({ diff: ['A /opt/hermes/agentic-notes'] })
    await expect(hotPatched(docker, 'hermes-iris')).resolves.toBe(false)
  })
})

